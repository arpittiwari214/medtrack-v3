/**
 * A single scheduled dose.
 *
 * The `_id` is the deterministic id from `@medtrack/shared`'s `doseIdFor` —
 * `${medicineId}_${epochSeconds}`. That makes generation idempotent at the
 * database level: regenerating a window is an upsert that changes nothing, and
 * two offline devices creating "the same" dose converge on one row rather than
 * duplicating.
 *
 * v3 relied on a secondary unique index over
 * `{userId, medicineId, date, scheduledTime}` plus a findOne-then-create in
 * application code. Because snoozing rewrote `scheduledTime`, that index both
 * failed to prevent duplicates and could collide on a legitimate snooze.
 */

import { Schema, model, type HydratedDocument, type InferSchemaType } from 'mongoose';

const doseEventSchema = new Schema(
  {
    /** Deterministic: `${medicineId}_${epochSeconds}`. Never randomly generated. */
    _id: { type: String, required: true },

    userId: { type: String, required: true, ref: 'User', index: true },
    medicineId: { type: String, required: true, ref: 'Medicine', index: true },

    /**
     * Authoritative instant the dose is due. Immutable after creation —
     * snoozing writes `snoozedUntil`, it does not move this.
     */
    scheduledAt: { type: Date, required: true },
    /** Wall-clock rendering of `scheduledAt`, for grouping and display. */
    localDate: { type: String, required: true },
    localTime: { type: String, required: true },
    timezone: { type: String, required: true },

    status: {
      type: String,
      required: true,
      default: 'scheduled',
      enum: ['scheduled', 'snoozed', 'taken', 'skipped', 'missed'],
    },
    takenAt: { type: Date, default: null },
    /** While snoozed, when the dose becomes due again. */
    snoozedUntil: { type: Date, default: null },
    snoozeCount: { type: Number, default: 0, min: 0 },
    skipReason: { type: String, default: null, maxlength: 500 },

    /** Denormalised so history survives a rename and renders offline. */
    medicineName: { type: String, required: true },
    medicineStrength: { type: String, default: '' },
    isCritical: { type: Boolean, default: false },

    /** True for a patient-logged dose on an `as_needed` medicine. */
    isAdHoc: { type: Boolean, default: false },

    /**
     * Precomputed instant this dose becomes missed, so the sweep is a plain
     * indexed range query rather than a scan plus per-row arithmetic.
     *
     * Normally `scheduledAt + graceMinutes`. Snoozing recomputes it from
     * `snoozedUntil`, so a deferred dose is not flagged against its original
     * time — the sweep and the state machine agree on when it is overdue.
     */
    missedAt: { type: Date, required: true },

    /** Grace period this dose was created with, so a later change to the medicine
     *  does not retroactively reinterpret history. */
    graceMinutes: { type: Number, required: true, default: 60, min: 5, max: 1440 },

    /** Guards against alerting twice for the same missed dose. */
    missAlertedAt: { type: Date, default: null },

    rev: { type: Number, default: 1 },
  },
  {
    timestamps: true,
    versionKey: false,
    // ids are supplied, never generated by Mongo.
    _id: false,
    toJSON: {
      virtuals: true,
      transform(_doc, ret: Record<string, unknown>) {
        ret['id'] = ret['_id'];
        delete ret['_id'];
        return ret;
      },
    },
  },
);

/** The dashboard and history queries: one user's doses over a date range. */
doseEventSchema.index({ userId: 1, localDate: -1, scheduledAt: 1 });

/** Per-medicine adherence breakdowns. */
doseEventSchema.index({ userId: 1, medicineId: 1, scheduledAt: -1 });

/**
 * Backs the miss sweep. Partial, so the index only holds doses that could still
 * become missed — a year of resolved history costs nothing to skip.
 */
doseEventSchema.index(
  { missedAt: 1 },
  {
    partialFilterExpression: { status: { $in: ['scheduled', 'snoozed'] } },
    name: 'pending_doses_by_missed_at',
  },
);

/** Incremental sync: everything changed since the client's cursor. */
doseEventSchema.index({ userId: 1, updatedAt: -1 });

export type DoseEventAttributes = InferSchemaType<typeof doseEventSchema>;
export type DoseEventDocument = HydratedDocument<DoseEventAttributes>;

export const DoseEvent = model('DoseEvent', doseEventSchema);
